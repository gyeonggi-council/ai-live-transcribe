def seed(reset: bool = False) -> None:
    supabase = create_client(settings.supabase_url, settings.supabase_key)

    if reset:
        supabase.table("dictionary").delete().neq("id", 0).execute()
        print("[RESET] 기존 사전 전체 삭제")

    existing = {
        r["wrong_text"]
        for r in (supabase.table("dictionary").select("wrong_text").limit(1000).execute().data or [])
    }

    rows = [
        {"wrong_text": term, "correct_text": term, "category": cat}
        for term, cat in BIAS_TERMS
    ] + [
        {"wrong_text": w, "correct_text": c, "category": "교정"}
        for w, c in CORRECTION_PAIRS
    ]

    new_rows = [r for r in rows if r["wrong_text"] not in existing]
    skipped = len(rows) - len(new_rows)
    if new_rows:
        # 입력 순서 보존 삽입 (글로서리 프롬프트 우선순위)
        supabase.table("dictionary").insert(new_rows).execute()
    print(f"[OK] 신규 {len(new_rows)}건 시드, 기존 {skipped}건 보존 (총 {len(rows)}건 정의)")


if __name__ == "__main__":
    seed(reset="--reset" in sys.argv)
