# 정상 문맥 — 오교정되면 안 되는 케이스(adversarial). 치환이 substring replace라
# '비슷한 정상 문자열'을 오염시키지 않는지 회귀 감시한다.
ADVERSARIAL_SAFE = [
    # '성원'을 포함하지만 정족수 선언이 아닌 정상 문장 — 손대지 않음
    "위원 여러분의 성원에 깊이 감사드립니다.",
    # '비상' 단독은 정상어 — '예비 비상 승인' 3-그램이 아니므로 보존
    "비상 대책 회의를 소집하였습니다.",
    "예비 전력과 비상 발전기를 점검하였습니다.",
    # '제안'·'설명'이 분리된 다른 의미 문장 — '제안 설명' 인접이 아니면 무관
    "이 제안에 대한 추가 설명이 필요합니다.",
    # '촉구' 정상 표기는 그대로
    "조속한 시행을 촉구하는 바입니다.",
    # 일반 '회계' 문맥
    "회계 처리 기준을 점검하였습니다.",
]


@pytest.mark.parametrize("text", ADVERSARIAL_SAFE)
def test_no_overcorrection_on_legitimate_text(dictionary, text):
    """정상 문맥은 의미가 바뀌지 않는다(절차어 외 일반어 보존).

    숫자 변환은 별개 기능이라 여기서는 '핵심 명사가 보존되는지'만 본다.
    """
    out = dictionary.correct(text)
    # 핵심 토큰이 사라지거나 엉뚱하게 바뀌지 않았는지
    for token in ("성원", "비상", "제안", "촉구", "회계"):
        if token in text:
            assert token in out, f"오교정: {text!r} → {out!r} ({token} 손상)"


